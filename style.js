// 3. DOM CONTENT LOADED & PAGE UTILITIES
// ==========================================================================
document.addEventListener("DOMContentLoaded", () => {

  // Apply saved or default language translation on initial load
  tApi.applyTranslations();

  // Close dropdown menu on outside clicks
  window.addEventListener('click', (event) => {
    if (!event.target.closest('.lang-dropdown-wrapper')) {
      const menu = document.getElementById("langMenu");
      if (menu && menu.classList.contains('show')) {
        menu.classList.remove('show');
      }
    }
  });

  // Accordion Toggle Logic
  const accordionHeaders = document.querySelectorAll(".accordion-header");
  accordionHeaders.forEach(header => {
    header.addEventListener("click", () => {
      const currentItem = header.parentElement;
      document.querySelectorAll(".accordion-item").forEach(item => {
        if (item !== currentItem) item.classList.remove("active");
      });
      currentItem.classList.toggle("active");
    });
  });

  // Election Countdown Clock (January 16, 2027)
  const targetDate = new Date("2027-01-16T08:00:00+01:00").getTime();
  function updateLiveClock() {
    const now = new Date().getTime();
    const difference = targetDate - now;

    const elDays = document.getElementById("cd-days");
    const elHours = document.getElementById("cd-hours");
    const elMinutes = document.getElementById("cd-minutes");
    const elSeconds = document.getElementById("cd-seconds");

    if (!elDays || !elHours || !elMinutes || !elSeconds) return;

    if (difference <= 0) {
      const container = document.querySelector(".countdown-container");
      if (container) {
        container.innerHTML = "<h3 style='color: #28a745;'>Elections Are Live Today!</h3>";
      }
      return;
    }

    elDays.textContent = String(Math.floor(difference / (1000 * 60 * 60 * 24))).padStart(2, "0");
    elHours.textContent = String(Math.floor((difference % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60))).padStart(2, "0");
    elMinutes.textContent = String(Math.floor((difference % (1000 * 60 * 60)) / (1000 * 60))).padStart(2, "0");
    elSeconds.textContent = String(Math.floor((difference % (1000 * 60)) / 1000)).padStart(2, "0");
  }
  updateLiveClock();
  setInterval(updateLiveClock, 1000);
});

