// 2. TRANSLATION ENGINE & API CLASS
// ==========================================================================
class TranslationAPI {
  constructor(defaultLang = 'en') {
    this.currentLang = localStorage.getItem('selected_lang') || defaultLang;
  }

  setLanguage(langCode, langName) {
    this.currentLang = langCode;
    localStorage.setItem('selected_lang', langCode);

    // Update Dropdown Display Button Text
    const label = document.getElementById('current-lang-text');
    if (label) label.innerText = langCode.toUpperCase();

    // Close Dropdown Menu
    const menu = document.getElementById("langMenu");
    if (menu) menu.classList.remove("show");

    // Execute translation swap across entire DOM
    this.applyTranslations();
  }

  applyTranslations() {
    const activeDict = siteTranslations[this.currentLang];
    const elements = document.querySelectorAll('[data-translate]');

    // Check if dictionary exists and has keys loaded
    if (activeDict && Object.keys(activeDict).length > 0) {
      elements.forEach(el => {
        const key = el.getAttribute('data-translate');
        if (activeDict[key]) {
          el.style.opacity = "0";
          setTimeout(() => {
            el.innerHTML = activeDict[key];
            el.style.opacity = "1";
          }, 120);
        } else if (siteTranslations['en'] && siteTranslations['en'][key]) {
          // Fallback to English key if specific local dictionary key is missing
          el.innerHTML = siteTranslations['en'][key];
        }
      });
    }

    // Trigger Google Translate engine for any remaining untranslated elements
    this.triggerGoogleTranslate(this.currentLang);
  }

  triggerGoogleTranslate(langCode) {
    const targetLang = googleLangMap[langCode] || langCode;
    const select = document.querySelector('.goog-te-combo');
    if (select) {
      select.value = targetLang;
      select.dispatchEvent(new Event('change'));
    }
  }
}

